function Set-Kubectl {
    <#
    .SYNOPSIS
        Quick function to install krew and stern

    .DESCRIPTION
        This function will check if krew and stern are installed, if not it will install them.

    .EXAMPLE
        Set-Kubectl

    .NOTES
        pretty straight forward.

        Author: Michiel VH
        Requires: kubectl to be installed on the system.

    .LINK
        kubectl plugin docs:
        https://kubernetes.io/docs/tasks/extend-kubectl/kubectl-plugins/

        krew - package manager for kubectl plugins:
        https://krew.sigs.k8s.io/

        kubectl windows installation:
        https://kubernetes.io/docs/tasks/tools/install-kubectl-windows/
    #>

    [CmdletBinding(SupportsShouldProcess)]
    param()

    # function definiton
    $Krew = kubectl krew version
    if (!$Krew -and $PSCmdlet.ShouldProcess('krew', 'Install with Chocolatey')) {
        choco install krew -y
    }

    $Stern = kubectl stern -v
    if (!$Stern -and $PSCmdlet.ShouldProcess('stern', 'Install kubectl plugin with krew')) {
        kubectl krew install stern
    }

    # Write the completion configuration to powershell profile
    if ($PSCmdlet.ShouldProcess($PROFILE, 'Append kubectl completion')) {
        kubectl completion powershell >> $PROFILE
    }

    # We need to add some more configurations to the profile that is not generated by the kubectl completion command
    # Under -WhatIf the profile may not exist yet, and Select-String throws on a missing path.
    $aliasSet = (Test-Path -LiteralPath $PROFILE) -and (Select-String -Path $PROFILE -Pattern '^\s*Set-Alias -Name k -Value kubectl' -Quiet -ErrorAction SilentlyContinue)
    if (-not $aliasSet) {

        $kubectlConfig = @"
Set-Alias -Name k -Value kubectl
Register-ArgumentCompleter -CommandName k -ScriptBlock `$__kubectlCompleterBlock
# Set-PSReadLineKeyHandler -Key Tab -Function Complete # probably not needed but adding for reference
"@

        if ($PSCmdlet.ShouldProcess($PROFILE, 'Add kubectl alias')) {
            Add-Content -Path $PROFILE -Value $kubectlConfig
        }
    }
    else {
        Write-Host "Alias already set in profile"
    }
}
